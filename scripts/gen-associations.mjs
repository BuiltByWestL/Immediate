// Generates the OS file associations from src/formats.json (the single list of file types):
//   src-tauri/windows/hooks.nsh      Windows installer: "Open with" + right-click entry, never the default app
//   src-tauri/tauri.macos.conf.json  macOS document types (rank Alternate: shows in Open With, never claims defaults)
//   src-tauri/tauri.linux.conf.json  Linux .desktop MimeType
//
// Usage: node scripts/gen-associations.mjs [--check]   (--check fails if the files are out of date)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";

const root = resolve(import.meta.dirname, "..");
const formats = JSON.parse(readFileSync(resolve(root, "src/formats.json"), "utf8"));
const check = process.argv.includes("--check");
const KINDS = { image: "Image", video: "Video", audio: "Audio" };

const entries = []; // { ext, kind, editable, mime }
for (const kind of Object.keys(KINDS)) {
  for (const [group, editable] of [["edit", true], ["view", false]]) {
    for (const [ext, mime] of Object.entries(formats[kind][group])) entries.push({ ext, kind, editable, mime });
  }
}

// ---- Windows (NSIS hooks, per-user, HKCU only) ------------------------------------------
const exe = "$INSTDIR\\${MAINBINARYNAME}.exe";
const cmd = `'"${exe}" "%1"'`;
const nsh = [];
const add = (s = "") => nsh.push(s);
add("; Generated by scripts/gen-associations.mjs from src/formats.json. Do not edit by hand.");
add(";");
add("; Registers Immediate under \"Open with\" and adds a right-click entry (\"Edit with Immediate\")");
add("; for every supported type, per user. It never changes which app opens a file by default:");
add("; that stays the user's choice (Settings > Apps > Default apps lists Immediate).");
add();
add("!macro IMMEDIATE_PROGID PROGID NAME");
add('  WriteRegStr HKCU "Software\\Classes\\${PROGID}" "" "${NAME}"');
add(`  WriteRegStr HKCU "Software\\Classes\\\${PROGID}\\DefaultIcon" "" "${exe},0"`);
add(`  WriteRegStr HKCU "Software\\Classes\\\${PROGID}\\shell\\open\\command" "" ${cmd}`);
add("!macroend");
add();
add("!macro IMMEDIATE_OPENWITH EXT PROGID");
add('  WriteRegStr HKCU "Software\\Classes\\.${EXT}\\OpenWithProgids" "${PROGID}" ""');
add('  WriteRegStr HKCU "Software\\Classes\\Applications\\${MAINBINARYNAME}.exe\\SupportedTypes" ".${EXT}" ""');
add('  WriteRegStr HKCU "Software\\Immediate\\Capabilities\\FileAssociations" ".${EXT}" "${PROGID}"');
add("!macroend");
add();
add("!macro IMMEDIATE_VERB EXT LABEL");
add('  WriteRegStr HKCU "Software\\Classes\\SystemFileAssociations\\.${EXT}\\shell\\Immediate" "" "${LABEL}"');
add(`  WriteRegStr HKCU "Software\\Classes\\SystemFileAssociations\\.\${EXT}\\shell\\Immediate" "Icon" "${exe},0"`);
add('  WriteRegStr HKCU "Software\\Classes\\SystemFileAssociations\\.${EXT}\\shell\\Immediate" "MultiSelectModel" "Player"');
add(`  WriteRegStr HKCU "Software\\Classes\\SystemFileAssociations\\.\${EXT}\\shell\\Immediate\\command" "" ${cmd}`);
add("!macroend");
add();
add("!macro IMMEDIATE_UNASSOC EXT PROGID");
add('  DeleteRegValue HKCU "Software\\Classes\\.${EXT}\\OpenWithProgids" "${PROGID}"');
add('  DeleteRegKey /ifempty HKCU "Software\\Classes\\.${EXT}\\OpenWithProgids"');
add('  DeleteRegKey /ifempty HKCU "Software\\Classes\\.${EXT}"');
add('  DeleteRegKey HKCU "Software\\Classes\\SystemFileAssociations\\.${EXT}\\shell\\Immediate"');
add("!macroend");
add();
add("!macro NSIS_HOOK_POSTINSTALL");
for (const [kind, name] of Object.entries(KINDS)) add(`  !insertmacro IMMEDIATE_PROGID "Immediate.${name}" "${name} file"`);
add('  WriteRegStr HKCU "Software\\Classes\\Applications\\${MAINBINARYNAME}.exe" "FriendlyAppName" "Immediate"');
add(`  WriteRegStr HKCU "Software\\Classes\\Applications\\\${MAINBINARYNAME}.exe\\DefaultIcon" "" "${exe},0"`);
add(`  WriteRegStr HKCU "Software\\Classes\\Applications\\\${MAINBINARYNAME}.exe\\shell\\open\\command" "" ${cmd}`);
add('  WriteRegStr HKCU "Software\\Immediate\\Capabilities" "ApplicationName" "Immediate"');
add('  WriteRegStr HKCU "Software\\Immediate\\Capabilities" "ApplicationDescription" "Open any media file, make a quick edit, save a file."');
add('  WriteRegStr HKCU "Software\\RegisteredApplications" "Immediate" "Software\\Immediate\\Capabilities"');
for (const e of entries) {
  add(`  !insertmacro IMMEDIATE_OPENWITH "${e.ext}" "Immediate.${KINDS[e.kind]}"`);
  if (!formats.noVerb.includes(e.ext)) {
    add(`  !insertmacro IMMEDIATE_VERB "${e.ext}" "${e.editable ? "Edit with Immediate" : "Open in Immediate"}"`);
  }
}
add("  ; Tell Explorer the associations changed (SHCNE_ASSOCCHANGED).");
add("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'");
add("!macroend");
add();
add("!macro NSIS_HOOK_PREUNINSTALL");
for (const e of entries) add(`  !insertmacro IMMEDIATE_UNASSOC "${e.ext}" "Immediate.${KINDS[e.kind]}"`);
for (const name of Object.values(KINDS)) add(`  DeleteRegKey HKCU "Software\\Classes\\Immediate.${name}"`);
add('  DeleteRegKey HKCU "Software\\Classes\\Applications\\${MAINBINARYNAME}.exe"');
add('  DeleteRegValue HKCU "Software\\RegisteredApplications" "Immediate"');
add('  DeleteRegKey HKCU "Software\\Immediate"');
add("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'");
add("!macroend");

// ---- macOS / Linux (Tauri bundle.fileAssociations, merged into tauri.conf.json per platform) ----
const byGroup = new Map(); // "image|edit" -> exts
const byMime = new Map(); // mime -> { exts, kind }
for (const e of entries) {
  const k = `${e.kind}|${e.editable}`;
  byGroup.set(k, [...(byGroup.get(k) ?? []), e.ext]);
  const m = byMime.get(e.mime) ?? { exts: [], kind: e.kind, editable: e.editable };
  m.exts.push(e.ext);
  byMime.set(e.mime, m);
}
const macos = {
  bundle: {
    fileAssociations: [...byGroup].map(([k, ext]) => {
      const [kind, editable] = k.split("|");
      return { ext, name: `${KINDS[kind]} file`, role: editable === "true" ? "Editor" : "Viewer", rank: "Alternate" };
    }),
  },
};
const linux = {
  bundle: {
    fileAssociations: [...byMime].map(([mimeType, m]) => ({ ext: m.exts, mimeType, name: `${KINDS[m.kind]} file` })),
  },
};

const outputs = [
  ["src-tauri/windows/hooks.nsh", nsh.join("\r\n") + "\r\n"],
  ["src-tauri/tauri.macos.conf.json", JSON.stringify(macos, null, 2) + "\n"],
  ["src-tauri/tauri.linux.conf.json", JSON.stringify(linux, null, 2) + "\n"],
];
let stale = 0;
for (const [rel, text] of outputs) {
  const file = resolve(root, rel);
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === text) continue;
  if (check) {
    console.error(`out of date: ${rel}`);
    stale++;
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${rel}`);
  }
}
if (stale) {
  console.error("Run: node scripts/gen-associations.mjs");
  process.exit(1);
}
console.log(`${entries.length} file types.`);
